// Copies third-party front-end assets into web/ so the Go binary can embed them:
//   - Plus Jakarta Sans woff2 (latin subset, only the weights the CSS uses) + OFL licence
//   - Lucide icons as Go template partials (inline SVG, CSP-safe) + ISC licence notice
// Run with `npm run vendor:assets`; the output is committed.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const FONT_WEIGHTS = [400, 600, 700, 800];
const ICONS = [
  "map-pin", "clock", "users", "calendar-days", "search", "menu", "x", "chevron-left",
  "chevron-right", "message-circle", "circle-check", "triangle-alert", "leaf", "sprout",
  "image", "info", "phone", "flag", "house", "wallet", "arrow-right", "list-checks",
  "hourglass", "shield-check", "book-open-check", "star", "message-square-quote",
];

mkdirSync("web/static/fonts", { recursive: true });
const fontDir = "node_modules/@fontsource/plus-jakarta-sans";
for (const w of FONT_WEIGHTS) {
  const name = `plus-jakarta-sans-latin-${w}-normal.woff2`;
  copyFileSync(`${fontDir}/files/${name}`, `web/static/fonts/${name}`);
}
copyFileSync(`${fontDir}/LICENSE`, "web/static/fonts/OFL.txt");

const licence = readFileSync("node_modules/lucide-static/LICENSE", "utf8").trim();
let out = `{{/*\nGenerated by scripts/vendor-assets.mjs from lucide-static. Do not edit.\nUse inside a sized element: <span class="icon size-5">{{template "i-map-pin"}}</span>\n\n${licence}\n*/}}\n`;
for (const name of ICONS) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, "utf8");
  const inner = svg
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>[\s\S]*$/, "")
    .replace(/\s*\n\s*/g, "")
    .trim();
  out += `{{define "i-${name}"}}<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${inner}</svg>{{end}}\n`;
}
writeFileSync("web/templates/partials/icons.html", out);
console.log(`fonts: ${FONT_WEIGHTS.length} weights, icons: ${ICONS.length}`);
